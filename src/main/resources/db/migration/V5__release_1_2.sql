-- 진행 비율 = (exp - 기존 현재레벨 기준) / (기존 다음레벨 기준 - 기존 현재레벨 기준), 0~1로 제한
-- 새 exp = 새 현재레벨 기준 + 비율 × 새 구간 크기 — 다음 레벨 기준 미만으로 제한해 이 보정만으로는 레벨이 바뀌지 않음
UPDATE commander c
JOIN commander_exp_rebase cur ON cur.commander_level = c.commander_level
JOIN commander_exp_rebase nxt ON nxt.commander_level = c.commander_level + 1
SET c.exp = cur.new_exp + LEAST(
        nxt.new_exp - cur.new_exp - 1,
        GREATEST(0, FLOOR((c.exp - cur.old_exp) * (nxt.new_exp - cur.new_exp) / (nxt.old_exp - cur.old_exp)))
    );

-- 최고 레벨(다음 레벨 없음)은 현재 레벨 기준 초과분을 그대로 유지
UPDATE commander c
JOIN commander_exp_rebase cur ON cur.commander_level = c.commander_level
SET c.exp = cur.new_exp + GREATEST(0, c.exp - cur.old_exp)
WHERE c.commander_level = (SELECT max_level FROM (SELECT MAX(commander_level) AS max_level FROM commander_exp_rebase) m);

